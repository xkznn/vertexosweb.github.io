export type Lang = "en" | "es" | "ar" | "ru" | "fr";

export const LANGS: { code: Lang; label: string; native: string }[] = [
  { code: "en", label: "English", native: "English" },
  { code: "es", label: "Spanish", native: "Español" },
  { code: "ar", label: "Arabic", native: "العربية" },
  { code: "ru", label: "Russian", native: "Русский" },
  { code: "fr", label: "French", native: "Français" },
];

export const LANGS_BY_CODE: Record<Lang, { code: Lang; label: string; native: string }> = {
  en: LANGS[0], es: LANGS[1], ar: LANGS[2], ru: LANGS[3], fr: LANGS[4],
};

const LANG_KEY = "vertex-lang";
const LEGACY_LANG_KEY = "vertex-language";
const LANG_SET_KEY = "vertex-language-set";
const VALID_LANGS: Lang[] = ["en", "es", "ar", "ru", "fr"];

export function readLang(): Lang {
  try {
    const raw = localStorage.getItem(LANG_KEY) ?? localStorage.getItem(LEGACY_LANG_KEY) ?? "en";
    return VALID_LANGS.includes(raw as Lang) ? (raw as Lang) : "en";
  } catch {
    return "en";
  }
}

export function saveLang(lang: Lang): void {
  try {
    localStorage.setItem(LANG_KEY, lang);
    localStorage.setItem(LANG_SET_KEY, "true");
  } catch { /* session still works */ }
}

export function localeOf(lang: Lang): string {
  switch (lang) {
    case "es": return "es-ES";
    case "ar": return "ar";
    case "ru": return "ru-RU";
    case "fr": return "fr-FR";
    default: return "en-US";
  }
}

