const dictionaries: Record<Lang, Dict> = { en, es, ar, ru, fr };

export function t(key: string): string {
  return dictionaries[LANG][key] ?? dictionaries.en[key] ?? key;
}

export function tf(key: string, vars: Record<string, string | number>): string {
  let out = t(key);
  for (const [k, v] of Object.entries(vars)) out = out.split(`{${k}}`).join(String(v));
  return out;
}

function pluralForm(lang: Lang, n: number): "one" | "few" | "other" {
  if (lang === "ru") {
    const mod10 = n % 10;
    const mod100 = n % 100;
    if (mod10 === 1 && mod100 !== 11) return "one";
    if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return "few";
    return "other";
  }
  return n === 1 ? "one" : "other";
}

export function tp(key: string, n: number): string {
  const form = pluralForm(LANG, n);
  const dict = dictionaries[LANG];
  const val = dict[`${key}.${form}`] ?? dict[`${key}.other`] ?? dictionaries.en[`${key}.other`] ?? t(key);
  return val.replace("{n}", String(n));
}